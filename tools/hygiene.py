"""Hygiene check for a public repository.

Without arguments it scans the working tree of the repository that contains
the current directory: every tracked file plus every untracked file that is
not ignored, so new files are covered before they are staged. With
``--range BASE..HEAD`` it also checks each commit of that range: the raw
header lines, the message and every file the commit adds or changes.

Checks:

- absolute local paths (any Windows drive path, a Windows device path to a
  drive, a volume, a UNC share or the global root after any device prefix
  (two backslashes and a question mark or a dot, or a backslash and two
  question marks), also with its backslashes escaped as in JSON, Linux,
  BSD, Solaris and macOS home folders, the root home folder, media mounts
  and pytest temporary folders named after the user, WSL drive mounts, and
  in text also Git Bash and Cygwin drive paths, all of them also with
  their slashes escaped as in JSON); a home folder counts only at the start
  of a path, not inside a URL or a relative path, also with its slashes
  escaped as in JSON, and also with backslashes, plain or doubled, as a
  Windows home folder without a drive; in text a home folder also counts
  below one to three other folders at the start of a path, as in a bind
  mount or on a network share; the root home folder counts with or without
  a separator after it, but not as the closing tag of an XML element named
  root; drive, home and Git Bash paths count after an escape sequence or a
  one-letter flag too; a Git Bash path does not start after a glob star;
- email addresses other than GitHub noreply addresses and GitHub's SSH user,
  quoted local parts included; an address glued to an allowed one is found
  too; GitHub's SSH user and noreply address stay exempt in text when only
  punctuation such as "/", "=", a quote or a backtick touches their front
  (as in an ssh:// URL), not a letter, digit, ".", "+", "-" or "_";
- non-ASCII characters outside ``NON_ASCII_ALLOW``;
- binary files, CR bytes in text files, and other control characters (C0
  except TAB and LF, and DEL) in text files and commit messages;
- a ``.gitleaksignore`` file anywhere;
- the inline gitleaks suppression marker;
- ``.gitleaks.toml`` and ``.gitattributes`` byte-identical to their canonical
  content (compared by SHA-256), at any depth; the two at the root are read
  straight from disk, tracked or not, and must exist;
- path names, of files and in the range also of folders: the text checks
  above plus control characters; the local path checks see the path with a
  leading slash, so a top-level ``home/...`` is found, and skip the Git Bash
  and Cygwin forms, so a top-level folder with a one-letter name is no
  finding;
- in file content and commit messages, host and user names as test reports
  write them: a hostname attribute other than localhost or empty, a
  sessioninfo id other than localhost, a dash and hex digits (a sessioninfo
  tag that does not end on its line and has no id there counts too), and a
  name attribute whose value is user.name; only in attribute syntax, a
  value in single or double quotes, also escaped by a backslash as in JSON,
  so prose that names them is no finding; the names ignore case in ASCII
  only;
- in the range: the emails of the first author and committer lines must be
  plain ASCII GitHub noreply addresses; every raw header line, signatures
  included, gets the local path, email and suppression marker checks (not
  the non-ASCII check, names may be non-ASCII; the base64 lines of a
  signature, also of the tag signature in a mergetag header, skip the Git
  Bash and Cygwin forms); commit messages, split into lines at CR, LF and
  CRLF, must carry no attribution trailer, no "generated with" or
  "generated by" line, and no directive that makes GitHub skip workflows
  (the bracketed skip forms or a skip-checks trailer); these and the
  suppression marker ignore case in ASCII only.

Each finding is one line, ``hygiene: path:line: [category] detail``. The
constant prefix keeps a path from being read as a workflow command, and a
hash sign in a path prints as ``\\x23``, so a path cannot carry the legacy
command form that the runner reads anywhere in a line. Line 0 means the
whole file. Matched text is never printed, so a public CI log does not
repeat what it reports. When the path name itself has a finding, the path
is shown only as ``path-sha256:`` and the first 12 hex digits of its
SHA-256. Header lines of a commit are reported as
``commit/<id>/header:<line>``. A line gets at most one finding per
category: the first column, and ``(+N more)`` when there are more.

Findings go to stdout. Every run writes ``hygiene: checked N files`` to
stderr, with ``, N commits`` added when ``--range`` is given, and then the
number of findings or the error.

Exit codes: 0 clean, 1 findings, 2 usage or git error, or any unexpected
error (only the exception type is printed). The findings collected before
an error are printed first.
"""

