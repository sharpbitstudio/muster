# SHA-256 of the canonical bytes of the pinned files:
#   .gitattributes = b"* text=auto eol=lf\n"
#   .gitleaks.toml = b"[extend]\nuseDefault = true\n"
PINNED = {
    ".gitattributes": "d60f352d0db1404c70afb4bb8b2ca3fd1c610572aa40720e8a0b7baa7885418c",
    ".gitleaks.toml": "27630a96d6c55755cc37620f3933d5cab94b1eb78a726a32e11212972525d76e",
}

# Non-ASCII characters allowed in file content, paths and commit messages.
# Empty on purpose: the repository is plain ASCII. Add a character only as an
# escape sequence, never as the literal character, with the reason in the
# commit message.
NON_ASCII_ALLOW: frozenset[str] = frozenset()


def path_start(word: str) -> str:
    """Lookbehind for the start of a path: not after a character in word, but
    after an escape such as \\n (as in JSON), or after a one-letter flag such
    as -I or -L that itself starts a word."""
    return rf"(?:(?<![{word}])|(?<=\\[A-Za-z])|(?<=(?<![{word}])-[A-Za-z]))"


# A slash, or a slash escaped as in JSON.
SLASH = r"\\?/"
# A backslash, or a backslash escaped as in JSON.
BACKSLASH = r"\\\\?"
# Either of the two.
SEPARATOR = "(?:" + SLASH + "|" + BACKSLASH + ")"


def ascii_nocase(word: str) -> str:
    """A pattern for word in any ASCII letter case. IGNORECASE would also
    take a non-ASCII look-alike, such as the Kelvin sign for a K."""
    return "".join(f"[{ch.upper()}{ch.lower()}]" for ch in word)


# A home folder. Only at the start of a path (see path_start): not after a
# word, a dot, a dash or a backslash, so a URL path or a relative path is no
# home folder, escaped as in JSON or not. Home roots under var, usr and
# export, and the macOS data volume, count too. Each separator may also be
# a backslash, plain or doubled as in JSON, mixed or not, so a Windows home
# path without a drive (after %SystemDrive% or a cd) counts; after a
# backslash the user name ends at the next backslash.
HOME_ROOT = (
    "(?:(?:" + SEPARATOR + "(?:var|usr|export))?" + SEPARATOR + "home"
    + "|(?:" + SEPARATOR + "System" + SEPARATOR + "Volumes" + SEPARATOR + "Data)?" + SEPARATOR + "Users)"
)
HOME_NAME = "(?:" + SLASH + r"[^\s/'\"<>]+|" + BACKSLASH + r"[^\s/\\'\"<>]+)"
HOME_RE = re.compile(path_start(r"\w.\\-") + HOME_ROOT + HOME_NAME)
# In text, a home root also counts below one to three other folders, as in
# a bind mount of a container, a home on a network share or a second macOS
# volume. That path starts where a path can start and not after a slash
# either, so neither a URL path nor a relative path is one. A folder name
# holds no colon, so an escape such as \t before a drive path is no folder.
# Each folder name is bounded and taken possessively, so the search stays
# linear. Text shaped like a route with a home or Users folder in it is found
# too, and so is a UNC share with such a folder.
HOME_TEXT_RE = re.compile(
    "(?:" + path_start(r"\w.\\-") + HOME_ROOT
    + "|" + path_start(r"\w./\\-") + "(?:" + SEPARATOR + r"[^\s/\\:'\"<>]{1,255}+){1,3}"
    + SEPARATOR + "(?:home|Users))" + HOME_NAME
)

# The patterns are phrased so that this file does not match them itself.
# Checked in text and in path names.
PATH_NAME_RES = (
    # Any drive path, also with the colon escaped by a backslash as in a Java
    # properties file. The drive letter may follow an escape such as \n or a
    # one-letter flag (see path_start), but not a letter or digit of a word,
    # so "https://" and "s3://" are no drive, nor a percent sign or a
    # backslash, so format and regex text such as "%s:" is none either.
    re.compile(path_start(r"A-Za-z0-9%\\") + r"[A-Za-z]\\?:[\\/]"),
    # A Windows device path: a device prefix (two backslashes, then "?" or
    # ".", then a backslash; or a backslash, two "?" and a backslash), each
    # backslash also doubled as in JSON, then a drive, a volume GUID, a UNC
    # share or the global root. A prefix followed by anything else, such as
    # regex text or a named pipe, is none.
    re.compile(
        BACKSLASH + r"(?:" + BACKSLASH + r"[?.]|\?\?)" + BACKSLASH
        + r"(?:[A-Za-z]:|" + ascii_nocase("Volume") + r"\{|(?:"
        + ascii_nocase("UNC") + "|" + ascii_nocase("GLOBALROOT") + ")" + BACKSLASH + ")"
    ),
    HOME_RE,
    # The root home folder, ending in a separator or before a character that
    # cannot continue the folder name, so a longer name such as rootfs is
    # none. The closing tag of an XML element named root, its slash escaped
    # as in JSON or not, is none either: only a "<" right before the slash
    # together with a ">" right after the name, so a shell redirect from a
    # file under the root home folder still counts.
    re.compile(
        path_start(r"\w.\\-") + "(?!(?<=<)" + SLASH + "root>)" + SLASH + "root" + "(?:" + SLASH + r"|(?![\w.-]))"
    ),
    # Folders named after the user outside a home root. Removable media
    # mounts, with the same start rule as above.
    re.compile(
        path_start(r"\w.\\-") + "(?:" + SLASH + "run)?" + SLASH + "media" + SLASH
        + r"[^\s/'\"<>]+" + SLASH
    ),
    # The pytest temporary root, which pytest puts in the temporary folder
    # the system gives (/tmp, /var/tmp, a macOS /private/var/folders path):
    # after any slash or backslash, escaped as in JSON or not, with no start
    # rule. The user name is at least one character and needs nothing after
    # it, so a root at the end of a path, before a space, a quote or ">",
    # or at the end of a line counts; code that builds one from an empty
    # name ("/pytest-of-" before a quote) does not.
    re.compile("(?:" + SLASH + "|" + BACKSLASH + ")pytest-of-" + r"[^\s/\\'\"<>]+"),
    # A WSL drive mount, its slashes also escaped as in JSON.
    re.compile(SLASH + "mnt" + SLASH + "[A-Za-z]" + SLASH),
)
# Checked in text only: a path name may well start with a one-letter folder.
# In text the home pattern also takes the folders above a home root.
LOCAL_PATH_RES = tuple(HOME_TEXT_RE if rx is HOME_RE else rx for rx in PATH_NAME_RES) + (
    # A Cygwin drive path, its slashes also escaped as in JSON.
    re.compile(SLASH + "cygdrive" + SLASH + "[A-Za-z]" + SLASH),
    # A Git Bash drive path: a one-letter root folder and at least one more
    # folder. The folder name starts with a word character, a dot or a dash,
    # and may then hold any character Windows allows in a name, spaces
    # included, except a single quote or a backtick, which quote short paths
    # in code and Markdown; it does not end in a space. Bounded (a name has
    # at most 255 characters) and possessive, so the search stays linear.
    # Other text of that shape is found too. The slashes may be escaped as
    # in JSON; the path does not start after a backslash either, so a match
    # cannot begin at the slash of an escaped one and skip the start rule.
    # Nor after a star, so a glob such as **/x/... is none.
    re.compile(
        path_start(r"\w./\\*-") + SLASH + "[A-Za-z]" + SLASH
        + r"""(?=[\w.-][^\x00-\x1f\x7f/\\:*?"<>|'`]{0,254}+(?<! )""" + SLASH + ")"
    ),
)
# No lookbehind: an address glued after another one is still found (see
# bad_email_columns). After the top-level domain only a letter or digit ends
# the match, so "pkg@1.0.rc1" is no address but an address followed by "_"
# or "-" is. The match is the complete address, and only a complete address
# can be exempt. A quoted local part does not start or end with a space, so
# code that joins two strings before an at sign is not one.
# An unquoted local part takes the dot and every RFC 5322 atext character.
# The local part, quoted or not, is bounded (at most 64 characters, as in
# RFC 5321) and taken possessively, and each domain label is bounded (at most
# 63), so a long line costs linear time; a longer local part is still found by
# its last 64 characters.
EMAIL_RE = re.compile(
    r'(?:"(?:[^"\\\s]|\\.)(?:[^"\\\r\n]|\\.){0,62}+(?<!\s)"|'
    r"[\w.!#$%&'*+/=?^`{|}~-]{1,64}+)"
    r"@[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?"
    r"(?:\.[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?)*\.[A-Za-z]{2,63}(?![A-Za-z0-9])"
)
# These patterns ignore case in ASCII only: under Unicode case folding a
# look-alike letter (such as the long s or the Kelvin sign) would match, and
# the attribution finding would print it. A line with such a letter is a
# non-ASCII finding instead.
MARKER_RE = re.compile(re.escape("gitleaks" + ":allow"), re.IGNORECASE | re.ASCII)
TRAILER_RE = re.compile(
    r"^\s*(co-authored-by|assisted-by|co-developed-by|generated-by|generated-with)\s*:", re.IGNORECASE | re.ASCII
)
GENERATED_RE = re.compile(r"^\W*generated\s+(with|by)\b", re.IGNORECASE | re.ASCII)
# GitHub runs no push or pull_request workflow when the head commit message
# carries one of these, and a rebase merge can make any commit the head.
# Assembled from parts so this file carries no directive itself.
CI_SKIP_WORDS = (("skip", "ci"), ("ci", "skip"), ("no", "ci"), ("skip", "actions"), ("actions", "skip"))
CI_SKIP_RE = re.compile(
    re.escape("[") + r"\s*(?:" + "|".join(a + r"[\s_-]*" + b for a, b in CI_SKIP_WORDS) + r")\s*" + re.escape("]"),
    re.IGNORECASE | re.ASCII,
)
SKIP_CHECKS_RE = re.compile(r"^\s*skip-checks\s*:\s*true\b", re.IGNORECASE | re.ASCII)
# C0 control characters except TAB, LF and CR (CR has its own check), and DEL.
CONTROL_RE = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")


# Host and user names in test reports (JUnit, JaCoCo and Surefire XML), in
# text only. Bound to attribute syntax, so prose that names an attribute is
# none: the name does not follow a word character, a dot, a colon or a dash,
# except right after an escape such as \t or \n in a string literal, and
# ignores case in ASCII only (see ascii_nocase); then "=", spaces around it
# allowed, and an opening quote, single or double, also escaped by a
# backslash as in a Python or JSON string. A fine value must be closed by
# the same quote, escaped the same way (XML_CLOSE), so any other value,
# unclosed or closed otherwise, counts. The same shape outside XML, such as
# an assignment in TOML or in a shell script, counts too, and so does a
# placeholder value such as one in braces. This file does not match the
# patterns itself: no attribute name in it is followed by "=" and a quote,
# and the sessioninfo element name never comes right after a "<".
def xml_attr(name: str) -> str:
    """An attribute name, "=" and the opening quote: group 1 is the
    backslash that escapes the quote, or empty, and group 2 the quote."""
    return r"(?:(?<![\w.:-])|(?<=\\[A-Za-z]))" + ascii_nocase(name) + r"\s*+=\s*+(\\?)([\"'])"


XML_CLOSE = r"\1\2"
# A JUnit host name: fine only when empty or localhost, closed. The
# lookahead holds the two fine values, so any other value is a match.
HOSTNAME_RE = re.compile(
    xml_attr("hostname") + "(?!(?:" + ascii_nocase("localhost") + ")?" + XML_CLOSE + ")", re.ASCII
)
# The opening tag of a JaCoCo session and its text up to the next "<" or ">"
# on the line, taken possessively so the scan stays linear; group 2 is the
# ">" that ends the tag on this line, or empty.
SESSIONINFO_RE = re.compile("<" + ascii_nocase("sessioninfo") + r"(?![\w.:-])([^<>]*+)(>?)", re.ASCII)
# An id attribute in that tag text; group 3 is set when the value is fine:
# localhost, a dash and hex digits, closed.
SESSION_ID_RE = re.compile(xml_attr("id") + "(localhost-[0-9A-Fa-f]++" + XML_CLOSE + ")?", re.ASCII)
# A property named after the user, as in a Surefire report, in any attribute
# order, or a keyword argument of the same name in code that builds one. The
# value ends where a name cannot go on, closed by any quote or not at all,
# so a mismatched close counts too and user.name.x does not.
USER_NAME_RE = re.compile(
    xml_attr("name") + ascii_nocase("user") + r"\." + ascii_nocase("name") + r"(?![\w.-])", re.ASCII
)


def session_id_ok(tag: str, closed: bool) -> bool:
    """Whether every id in the text of a sessioninfo tag is fine. A tag with
    no id is fine only when it ends on its line: otherwise the id may be on
    the next one."""
    ids = list(SESSION_ID_RE.finditer(tag))
    return all(m.group(3) is not None for m in ids) if ids else closed


NOREPLY_SUFFIX = "@users.noreply.github.com"
NOREPLY_RE = re.compile(r"[^@\s]+" + re.escape(NOREPLY_SUFFIX), re.IGNORECASE)
GITHUB_NOREPLY = "noreply" + "@github.com"
# GitHub's SSH user, as in clone URLs; not a person. Exempt in text, never as
# a commit identity.
GITHUB_SSH_USER = "git" + "@github.com"

# Dependabot adds this exact line to every commit; its address is exempt
# from the email check in commit messages, on this line only.
DEPENDABOT_SIGNOFF = "Signed-off-by: dependabot[bot] <" + "support" + "@github.com>"

# "author|committer <name> <<email>> <seconds> <zone>" in a raw commit header.
# The first bracket pair is the email, as git reads it; any other shape does
# not match, and a missing email fails the check.
IDENTITY_RE = re.compile(rb"(author|committer) [^<>]*<([^<>]*)> -?\d+ [+-]\d{4}")
# A continuation line of base64 in a signature block of a commit header.
SIGNATURE_LINE_RE = re.compile(r" [A-Za-z0-9+/=]+")
# A commit message is split into lines at any of these, so a bare CR cannot
# hide a line from the checks anchored at the start of a line.
MESSAGE_LINE_RE = re.compile(r"\r\n|\r|\n")

MODE_GITLINK = "160000"
MODE_TREE = "040000"


class GitError(Exception):
    pass


class UsageError(Exception):
    pass


def git(top: str | None, *args: str) -> bytes:
    try:
        r = subprocess.run(["git", *args], cwd=top, capture_output=True)
    except OSError as e:
        raise GitError(f"cannot run git: {e}") from None
    if r.returncode != 0:
        msg = r.stderr.decode("utf-8", "replace").strip() or f"exit {r.returncode}"
        raise GitError(f"git {args[0]}: {msg}")
    return r.stdout


def safe(text: str) -> str:
    """Printable-ASCII rendering of a path or name for the report. The hash
    sign is escaped too: the runner reads "##[" as a workflow command
    anywhere in a line."""
    out = []
    for ch in text:
        o = ord(ch)
        if 0x20 <= o <= 0x7E and ch != "#":
            out.append(ch)
        elif o < 0x80:
            out.append(f"\\x{o:02x}")
        elif o <= 0xFFFF:
            out.append(f"\\u{o:04x}")
        else:
            out.append(f"\\U{o:08x}")
    return "".join(out)


# An allowed address is plain ASCII: case folding under IGNORECASE would
# otherwise let a non-ASCII letter stand in for an ASCII one.
def identity_allowed(addr: str) -> bool:
    return addr.isascii() and (addr.lower() == GITHUB_NOREPLY or NOREPLY_RE.fullmatch(addr) is not None)


# Punctuation that the unquoted local part takes but that often only touches
# the front of an address in text: the slashes of an ssh:// URL, a quote or
# backtick, an "=" or a "*". A letter, digit, ".", "+", "-" or "_" before an
# exempt address makes it another address.
EXEMPT_LEAD = "!#$%&'*/=?^`{|}~"


def email_allowed(addr: str) -> bool:
    return addr.isascii() and (
        identity_allowed(addr) or addr.lstrip(EXEMPT_LEAD).lower() in (GITHUB_SSH_USER, GITHUB_NOREPLY)
    )


def bad_email_columns(text: str) -> list[int]:
    """Columns of the addresses in text that are not allowed. After an
    allowed address the search resumes right after its last at sign, since
    its domain may be the local part of a glued address; after any other
    address it resumes at its end. Allowed addresses are short, so going
    back into one keeps the scan linear."""
    cols = []
    pos = 0
    while m := EMAIL_RE.search(text, pos):
        if email_allowed(m.group(0)):
            pos = m.start() + m.group(0).rindex("@") + 1
        else:
            cols.append(m.start() + 1)
            pos = m.end()
    return cols


def path_location(path: str, suffix: str) -> str:
    digest = hashlib.sha256(path.encode("utf-8", "surrogateescape")).hexdigest()
    return f"path-sha256:{digest[:12]}{suffix}"


class Report:
    def __init__(self) -> None:
        self.lines: list[str] = []
        self.files = 0
        self.commits = 0

    def add(self, where: str, line: int, category: str, detail: str) -> None:
        self.lines.append(f"hygiene: {safe(where)}:{line}: [{category}] {detail}")

    def columns(self, where: str, line: int, category: str, detail: str, cols: list[int]) -> None:
        """One finding for all hits of a category on a line: the first column,
        and how many more there are."""
        if cols:
            more = f" (+{len(cols) - 1} more)" if len(cols) > 1 else ""
            self.add(where, line, category, f"{detail} at column {min(cols)}{more}")

    def leaks(self, line: str, where: str, n: int, *, emails: bool = True, paths: tuple = LOCAL_PATH_RES) -> None:
        """Local path, email and suppression marker checks on one line."""
        cols = [m.start() + 1 for rx in paths for m in rx.finditer(line)]
        self.columns(where, n, "abs-path", "absolute local path", cols)
        if emails and "@" in line:
            self.columns(where, n, "email", "email address not allowed", bad_email_columns(line))
        cols = [m.start() + 1 for m in MARKER_RE.finditer(line)]
        self.columns(where, n, "suppression-marker", "inline gitleaks suppression marker", cols)

    def names(self, line: str, where: str, n: int) -> None:
        """Host and user name checks on one line of text."""
        cols = [m.start() + 1 for m in HOSTNAME_RE.finditer(line)]
        self.columns(where, n, "hostname", "hostname attribute other than localhost or empty", cols)
        cols = [
            m.start() + 1 for m in SESSIONINFO_RE.finditer(line) if not session_id_ok(m.group(1), bool(m.group(2)))
        ]
        self.columns(where, n, "sessioninfo", "sessioninfo tag without a localhost-<hex> id", cols)
        cols = [m.start() + 1 for m in USER_NAME_RE.finditer(line)]
        self.columns(where, n, "user-name", "user.name property", cols)

    def text(self, text: str, where: str, *, message: bool = False) -> None:
        """Line checks on decoded text: file content or a commit message."""
        lines = MESSAGE_LINE_RE.split(text) if message else text.split("\n")
        for n, line in enumerate(lines, 1):
            self.leaks(line, where, n, emails=not (message and line == DEPENDABOT_SIGNOFF))
            self.names(line, where, n)
            cols = [col for col, ch in enumerate(line, 1) if ord(ch) > 127 and ch not in NON_ASCII_ALLOW]
            self.columns(where, n, "non-ascii", "non-ASCII character", cols)
            cols = [m.start() + 1 for m in CONTROL_RE.finditer(line)]
            self.columns(where, n, "control", "control character", cols)
            if message:
                m = CI_SKIP_RE.search(line)
                if m:
                    self.add(where, n, "ci-skip", f"CI skip directive at column {m.start() + 1}")
                if SKIP_CHECKS_RE.search(line):
                    self.add(where, n, "ci-skip", "'skip-checks' trailer")
                m = TRAILER_RE.search(line)
                if m:
                    self.add(where, n, "attribution", f"'{m.group(1).lower()}' trailer")
                m = GENERATED_RE.search(line)
                if m:
                    self.add(where, n, "attribution", f"'generated {m.group(1).lower()}' line")

    def path(self, path: str, suffix: str = "") -> str:
        """Checks on the path name itself. Returns the location to report the
        file under: the path, or its hash when the path name has a finding."""
        hits = []
        if any(rx.search("/" + path) for rx in PATH_NAME_RES):
            hits.append(("abs-path", "absolute local path in the path"))
        if bad_email_columns(path):
            hits.append(("email", "email address not allowed in the path"))
        if MARKER_RE.search(path):
            hits.append(("suppression-marker", "inline gitleaks suppression marker in the path"))
        if any(ord(ch) > 127 and ch not in NON_ASCII_ALLOW for ch in path):
            hits.append(("non-ascii", "non-ASCII character in the path"))
        if any(ord(ch) < 0x20 or ord(ch) == 0x7F for ch in path):
            hits.append(("path-control", "control character in the path"))
        where = path_location(path, suffix) if hits else path + suffix
        for category, detail in hits:
            self.add(where, 0, category, detail)
        if path.rsplit("/", 1)[-1].lower() == ".gitleaksignore":
            self.add(where, 0, "gitleaksignore", ".gitleaksignore file is not allowed")
        return where

    def blob(self, path: str, data: bytes, where: str, *, pin: bool = True) -> None:
        """Checks on the bytes of one file."""
        base = path.rsplit("/", 1)[-1].lower()
        if pin and base in PINNED:
            digest = hashlib.sha256(data).hexdigest()
            if digest != PINNED[base]:
                self.add(where, 0, "pin", f"{base} differs from the canonical content (sha256 {digest})")
        if b"\0" in data:
            self.add(where, 0, "binary", "binary file")
            return
        cr = data.find(b"\r")
        if cr >= 0:
            self.add(where, data.count(b"\n", 0, cr) + 1, "crlf", "CR byte in a text file")
        self.text(data.decode("utf-8", "replace"), where)

    def identity(self, raw: bytes, where: str) -> None:
        """Author and committer emails in a raw commit object: the first
        author line and the first committer line count, as git reads them,
        and must have the expected shape."""
        lines = raw.partition(b"\n\n")[0].split(b"\n")
        for role in ("author", "committer"):
            line = next((x for x in lines if x.startswith(role.encode() + b" ")), b"")
            m = IDENTITY_RE.fullmatch(line)
            if m is None:
                self.add(where, 0, "identity-email", f"{role} line is missing or malformed")
            elif not identity_allowed(m.group(2).decode("utf-8", "surrogateescape")):
                self.add(where, 0, "identity-email", f"{role} email is not a GitHub noreply address")

    def header(self, raw: bytes, where: str) -> None:
        """Leak checks on every raw header line of a commit object, signature
        blocks and the identity lines included, so an armor header or a
        second identity line is covered too. No non-ASCII check: names may be
        non-ASCII. The base64 lines of a signature block, and those of the
        armored signature of the tag inside a mergetag header, skip the Git
        Bash and Cygwin forms, which random base64 matches now and then; the
        other lines of a mergetag header get every check."""
        signature = mergetag = armor = False
        for n, line in enumerate(raw.partition(b"\n\n")[0].split(b"\n"), 1):
            if not line.startswith(b" "):
                signature = line.startswith((b"gpgsig ", b"gpgsig-sha256 "))
                mergetag = line.startswith(b"mergetag ")
                armor = False
            elif mergetag and line.startswith(b" -----BEGIN "):
                armor = True
            elif mergetag and line.startswith(b" -----END "):
                armor = False
            text = line.decode("utf-8", "replace")
            if (signature or armor) and SIGNATURE_LINE_RE.fullmatch(text):
                self.leaks(text, where, n, paths=PATH_NAME_RES)
            else:
                self.leaks(text, where, n)


def split_z(raw: bytes) -> list[str]:
    return [p.decode("utf-8", "surrogateescape") for p in raw.split(b"\0") if p]


def scan_tree(top: str, rep: Report) -> None:
    raw = git(top, "ls-files", "-z", "--cached", "--others", "--exclude-standard")
    paths = sorted(set(split_z(raw)))
    # The root pins are read from disk whether git lists them or not, so an
    # ignore rule cannot hide a changed one.
    for name, digest in PINNED.items():
        full = os.path.join(top, name)
        if os.path.islink(full):
            data = os.fsencode(os.readlink(full))
        elif os.path.isfile(full):
            with open(full, "rb") as f:
                data = f.read()
        else:
            rep.add(name, 0, "pin", f"{name} is missing")
            continue
        actual = hashlib.sha256(data).hexdigest()
        if actual != digest:
            rep.add(name, 0, "pin", f"{name} differs from the canonical content (sha256 {actual})")
    for path in paths:
        where = rep.path(path)
        full = os.path.join(top, *path.split("/"))
        if os.path.islink(full):
            data = os.fsencode(os.readlink(full))
        elif os.path.isfile(full):
            with open(full, "rb") as f:
                data = f.read()
        else:
            continue  # deleted from the working tree, or a submodule folder
        rep.files += 1
        rep.blob(path, data, where, pin=path not in PINNED)


def resolve(top: str, rev: str) -> str:
    try:
        return git(top, "rev-parse", "--verify", "--end-of-options", f"{rev}^{{commit}}").decode().strip()
    except GitError:
        raise GitError(f"not a commit: {rev}") from None


def scan_range(top: str, spec: str, rep: Report) -> None:
    base_rev, sep, head_rev = spec.partition("..")
    if not sep or not base_rev or not head_rev or head_rev.startswith("."):
        raise UsageError(f"--range must be BASE..HEAD, got {spec!r}")
    base = resolve(top, base_rev)
    head = resolve(top, head_rev)
    # Parents before children, so a file is reported at the commit that added it.
    rows = git(top, "rev-list", "--topo-order", "--reverse", "--parents", f"{base}..{head}").decode().split("\n")
    seen: set[tuple[str, str, bool]] = set()
    for row in filter(None, rows):
        sha, *parents = row.split()
        short = sha[:12]
        raw = git(top, "cat-file", "commit", sha)
        rep.commits += 1
        rep.identity(raw, f"commit/{short}")
        rep.header(raw, f"commit/{short}/header")
        message = raw.partition(b"\n\n")[2]
        rep.text(message.decode("utf-8", "replace"), f"commit/{short}", message=True)
        # -t lists the trees too, so the name of a tree entry (even one that
        # points at an empty tree) gets the path name checks.
        opts = ("diff-tree", "-r", "-t", "-z", "--no-commit-id", "--no-renames", "--diff-filter=d")
        if parents:
            diff = git(top, *opts, parents[0], sha)
        else:
            diff = git(top, *opts, "--root", sha)
        fields = split_z(diff)
        for meta, path in zip(fields[0::2], fields[1::2]):
            _, new_mode, _, blob, _ = meta.lstrip(":").split(" ")
            # A gitlink or a tree is never read, so it does not stand in for
            # a file with the same id at the same path in a later commit.
            content = new_mode not in (MODE_GITLINK, MODE_TREE)
            if (path, blob, content) in seen:
                continue
            seen.add((path, blob, content))
            where = rep.path(path, f"@{short}")
            if content:
                rep.blob(path, git(top, "cat-file", "blob", blob), where)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="hygiene.py", description="Public repository hygiene check.")
    ap.add_argument("--range", metavar="BASE..HEAD", help="also check the commits of this range")
    args = ap.parse_args(argv)
    rep = Report()
    error = None
    try:
        top = git(None, "rev-parse", "--show-toplevel").decode("utf-8", "surrogateescape").strip()
        scan_tree(top, rep)
        if args.range is not None:
            scan_range(top, args.range, rep)
    except (UsageError, GitError) as e:
        error = safe(str(e))
    except Exception as e:
        # The message of an unexpected error may carry a path or file content.
        error = f"unexpected {type(e).__name__}"
    for line in rep.lines:
        print(line)
    sys.stdout.flush()
    commits = f", {rep.commits} commits" if args.range is not None else ""
    print(f"hygiene: checked {rep.files} files{commits}", file=sys.stderr)
    if error is not None:
        print(f"hygiene.py: {error}", file=sys.stderr)
        return 2
    if rep.lines:
        print(f"hygiene: {len(rep.lines)} finding(s)", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
