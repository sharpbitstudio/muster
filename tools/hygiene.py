#!/usr/bin/env python3
"""Hygiene check for a public repository.

Without arguments it scans the working tree of the repository that contains
the current directory: every tracked file plus every untracked file that is
not ignored, so new files are covered before they are staged. With
``--range BASE..HEAD`` it also checks each commit of that range: the raw
header lines, the message and every file the commit adds or changes.

Checks:

- absolute local paths (any Windows drive path, Linux and macOS home
  folders, the root home folder, WSL drive mounts, and in text also Git Bash
  and Cygwin drive paths); a home folder counts only at the start of a path,
  also after an escape sequence or a one-letter flag, not inside a URL or a
  relative path;
- email addresses other than GitHub noreply addresses and GitHub's SSH user,
  quoted local parts included; an address glued to an allowed one is found
  too;
- non-ASCII characters outside ``NON_ASCII_ALLOW``;
- binary files, CR bytes in text files, and other control characters (C0
  except TAB and LF, and DEL) in text files and commit messages;
- a ``.gitleaksignore`` file anywhere;
- the inline gitleaks suppression marker;
- ``.gitleaks.toml`` and ``.gitattributes`` byte-identical to their canonical
  content (compared by SHA-256), at any depth; the two at the root are read
  straight from disk, tracked or not, and must exist;
- path names: the text checks above plus control characters; the local
  path checks see the path with a leading slash, so a top-level ``home/...``
  is found, and skip the Git Bash and Cygwin forms, so a top-level folder
  with a one-letter name is no finding;
- in the range: author and committer emails must be GitHub noreply
  addresses; every raw header line, signatures included, gets the local
  path, email and suppression marker checks (not the non-ASCII check, names
  may be non-ASCII); commit messages, split into lines at CR, LF and CRLF,
  must carry no attribution trailer, no "generated with" or "generated by"
  line, and no directive that makes GitHub skip workflows (the bracketed
  skip forms or a skip-checks trailer).

Each finding is one line, ``hygiene: path:line: [category] detail``; the
constant prefix keeps a path from being read as a workflow command. Line 0
means the whole file. Matched text is never printed, so a public CI log does
not repeat what it reports. When the path name itself has a finding, the
path is shown only as ``path-sha256:`` and the first 12 hex digits of its
SHA-256. Header lines of a commit are reported as
``commit/<id>/header:<line>``. A line gets at most one finding per
category: the first column, and ``(+N more)`` when there are more.

Findings go to stdout. Every run writes ``hygiene: checked N files`` to
stderr, with ``, N commits`` added when ``--range`` is given, and then the
number of findings or the error.

Exit codes: 0 clean, 1 findings, 2 usage or git error, or any unexpected
error (only the exception type is printed). The findings collected before
an error are printed first.
"""

from __future__ import annotations

import argparse
import hashlib
import os
import re
import subprocess
import sys

# Checked before any pattern is compiled: older versions reject the
# possessive quantifiers below with re.error.
MIN_PYTHON = (3, 11)
if sys.version_info < MIN_PYTHON:
    print("hygiene.py needs Python 3.11 or newer", file=sys.stderr)
    sys.exit(2)

# SHA-256 of the canonical bytes of the pinned files:
#   .gitattributes = b"* text=auto eol=lf\n"
#   .gitleaks.toml = b"[extend]\nuseDefault = true\n"
PINNED = {
    ".gitattributes": "d60f352d0db1404c70afb4bb8b2ca3fd1c610572aa40720e8a0b7baa7885418c",
    ".gitleaks.toml": "27630a96d6c55755cc37620f3933d5cab94b1eb78a726a32e11212972525d76e",
}

# Non-ASCII characters allowed in file content, paths and commit messages.
# Empty on purpose: the repository is plain ASCII. Add a character only as an
# escape sequence, never as the literal character, with the reason in the
# commit message.
NON_ASCII_ALLOW: frozenset[str] = frozenset()


def path_start(word: str) -> str:
    """Lookbehind for the start of a path: not after a character in word, but
    after an escape such as \\n (as in JSON), or after a one-letter flag such
    as -I or -L that itself starts a word."""
    return rf"(?:(?<![{word}])|(?<=\\[A-Za-z])|(?<=(?<![{word}])-[A-Za-z]))"


# The patterns are phrased so that this file does not match them itself.
# Checked in text and in path names.
PATH_NAME_RES = (
    # Any drive path. The drive letter may follow an escape such as \n, but
    # not a letter or digit of a word, so "https://" and "s3://" are no drive.
    re.compile(r"(?:(?<![A-Za-z0-9])|(?<=\\[A-Za-z]))[A-Za-z]:[\\/]"),
    # Only at the start of a path (see path_start): not after a word, a dot
    # or a dash, so a URL path or a relative path is no home folder.
    re.compile(path_start(r"\w.-") + r"/(?:home|Users)/[^\s/'\"<>]+"),
    re.compile(path_start(r"\w.-") + "/" + "root/"),
    re.compile(r"/mnt/[A-Za-z]/"),
)
# Checked in text only: a path name may well start with a one-letter folder.
LOCAL_PATH_RES = PATH_NAME_RES + (
    re.compile(r"/cygdrive/[A-Za-z]/"),
    # A Git Bash drive path: a one-letter root folder and at least one more
    # folder, whose name may hold spaces after its first character but does
    # not end in one. Bounded (a name has at most 255 characters) and
    # possessive, so the search stays linear. Other text of that shape is
    # found too.
    re.compile(path_start(r"\w./-") + r"/[A-Za-z]/(?=[\w.-][\w .-]{0,254}+(?<! )/)"),
)
# No lookbehind: an address glued after another one is still found (see
# bad_email_columns). After the top-level domain only a letter or digit ends
# the match, so "pkg@1.0.rc1" is no address but an address followed by "_"
# or "-" is. The match is the complete address, and only a complete address
# can be exempt. A quoted local part does not start or end with a space, so
# code that joins two strings before an at sign is not one.
# An unquoted local part takes the dot and every RFC 5322 atext character.
# The local part, quoted or not, is bounded (at most 64 characters, as in
# RFC 5321) and taken possessively, and each domain label is bounded (at most
# 63), so a long line costs linear time; a longer local part is still found by
# its last 64 characters.
EMAIL_RE = re.compile(
    r'(?:"(?:[^"\\\s]|\\.)(?:[^"\\\r\n]|\\.){0,62}+(?<!\s)"|'
    r"[\w.!#$%&'*+/=?^`{|}~-]{1,64}+)"
    r"@[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?"
    r"(?:\.[A-Za-z0-9](?:[A-Za-z0-9-]{0,61}[A-Za-z0-9])?)*\.[A-Za-z]{2,63}(?![A-Za-z0-9])"
)
MARKER_RE = re.compile(re.escape("gitleaks" + ":allow"), re.IGNORECASE)
TRAILER_RE = re.compile(
    r"^\s*(co-authored-by|assisted-by|co-developed-by|generated-by|generated-with)\s*:", re.IGNORECASE
)
GENERATED_RE = re.compile(r"^\W*generated\s+(with|by)\b", re.IGNORECASE)
# GitHub runs no push or pull_request workflow when the head commit message
# carries one of these, and a rebase merge can make any commit the head.
# Assembled from parts so this file carries no directive itself.
CI_SKIP_WORDS = (("skip", "ci"), ("ci", "skip"), ("no", "ci"), ("skip", "actions"), ("actions", "skip"))
CI_SKIP_RE = re.compile(
    re.escape("[") + r"\s*(?:" + "|".join(a + r"[\s_-]*" + b for a, b in CI_SKIP_WORDS) + r")\s*" + re.escape("]"),
    re.IGNORECASE,
)
SKIP_CHECKS_RE = re.compile(r"^\s*skip-checks\s*:\s*true\b", re.IGNORECASE)
# C0 control characters except TAB, LF and CR (CR has its own check), and DEL.
CONTROL_RE = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")

NOREPLY_SUFFIX = "@users.noreply.github.com"
NOREPLY_RE = re.compile(r"[^@\s]+" + re.escape(NOREPLY_SUFFIX), re.IGNORECASE)
GITHUB_NOREPLY = "noreply" + "@github.com"
# GitHub's SSH user, as in clone URLs; not a person. Exempt in text, never as
# a commit identity.
GITHUB_SSH_USER = "git" + "@github.com"

# Dependabot adds this exact line to every commit; its address is exempt
# from the email check in commit messages, on this line only.
DEPENDABOT_SIGNOFF = "Signed-off-by: dependabot[bot] <" + "support" + "@github.com>"

# "author|committer <name> <<email>> <seconds> <zone>" in a raw commit header.
# The first bracket pair is the email, as git reads it; any other shape does
# not match, and a missing email fails the check.
IDENTITY_RE = re.compile(rb"(author|committer) [^<>]*<([^<>]*)> -?\d+ [+-]\d{4}")
# A commit message is split into lines at any of these, so a bare CR cannot
# hide a line from the checks anchored at the start of a line.
MESSAGE_LINE_RE = re.compile(r"\r\n|\r|\n")

MODE_GITLINK = "160000"


class GitError(Exception):
    pass


class UsageError(Exception):
    pass


def git(top: str | None, *args: str) -> bytes:
    try:
        r = subprocess.run(["git", *args], cwd=top, capture_output=True)
    except OSError as e:
        raise GitError(f"cannot run git: {e}") from None
    if r.returncode != 0:
        msg = r.stderr.decode("utf-8", "replace").strip() or f"exit {r.returncode}"
        raise GitError(f"git {args[0]}: {msg}")
    return r.stdout


def safe(text: str) -> str:
    """Printable-ASCII rendering of a path or name for the report."""
    out = []
    for ch in text:
        o = ord(ch)
        if 0x20 <= o <= 0x7E:
            out.append(ch)
        elif o < 0x80:
            out.append(f"\\x{o:02x}")
        elif o <= 0xFFFF:
            out.append(f"\\u{o:04x}")
        else:
            out.append(f"\\U{o:08x}")
    return "".join(out)


def identity_allowed(addr: str) -> bool:
    return addr.lower() == GITHUB_NOREPLY or NOREPLY_RE.fullmatch(addr) is not None


def email_allowed(addr: str) -> bool:
    return identity_allowed(addr) or addr.lower() == GITHUB_SSH_USER


def bad_email_columns(text: str) -> list[int]:
    """Columns of the addresses in text that are not allowed. After an
    allowed address the search resumes right after its last at sign, since
    its domain may be the local part of a glued address; after any other
    address it resumes at its end. Allowed addresses are short, so going
    back into one keeps the scan linear."""
    cols = []
    pos = 0
    while m := EMAIL_RE.search(text, pos):
        if email_allowed(m.group(0)):
            pos = m.start() + m.group(0).rindex("@") + 1
        else:
            cols.append(m.start() + 1)
            pos = m.end()
    return cols


def path_location(path: str, suffix: str) -> str:
    digest = hashlib.sha256(path.encode("utf-8", "surrogateescape")).hexdigest()
    return f"path-sha256:{digest[:12]}{suffix}"


class Report:
    def __init__(self) -> None:
        self.lines: list[str] = []
        self.files = 0
        self.commits = 0

    def add(self, where: str, line: int, category: str, detail: str) -> None:
        self.lines.append(f"hygiene: {safe(where)}:{line}: [{category}] {detail}")

    def columns(self, where: str, line: int, category: str, detail: str, cols: list[int]) -> None:
        """One finding for all hits of a category on a line: the first column,
        and how many more there are."""
        if cols:
            more = f" (+{len(cols) - 1} more)" if len(cols) > 1 else ""
            self.add(where, line, category, f"{detail} at column {min(cols)}{more}")

    def leaks(self, line: str, where: str, n: int, *, emails: bool = True) -> None:
        """Local path, email and suppression marker checks on one line."""
        cols = [m.start() + 1 for rx in LOCAL_PATH_RES for m in rx.finditer(line)]
        self.columns(where, n, "abs-path", "absolute local path", cols)
        if emails and "@" in line:
            self.columns(where, n, "email", "email address not allowed", bad_email_columns(line))
        cols = [m.start() + 1 for m in MARKER_RE.finditer(line)]
        self.columns(where, n, "suppression-marker", "inline gitleaks suppression marker", cols)

    def text(self, text: str, where: str, *, message: bool = False) -> None:
        """Line checks on decoded text: file content or a commit message."""
        lines = MESSAGE_LINE_RE.split(text) if message else text.split("\n")
        for n, line in enumerate(lines, 1):
            self.leaks(line, where, n, emails=not (message and line == DEPENDABOT_SIGNOFF))
            cols = [col for col, ch in enumerate(line, 1) if ord(ch) > 127 and ch not in NON_ASCII_ALLOW]
            self.columns(where, n, "non-ascii", "non-ASCII character", cols)
            cols = [m.start() + 1 for m in CONTROL_RE.finditer(line)]
            self.columns(where, n, "control", "control character", cols)
            if message:
                m = CI_SKIP_RE.search(line)
                if m:
                    self.add(where, n, "ci-skip", f"CI skip directive at column {m.start() + 1}")
                if SKIP_CHECKS_RE.search(line):
                    self.add(where, n, "ci-skip", "'skip-checks' trailer")
                m = TRAILER_RE.search(line)
                if m:
                    self.add(where, n, "attribution", f"'{m.group(1).lower()}' trailer")
                m = GENERATED_RE.search(line)
                if m:
                    self.add(where, n, "attribution", f"'generated {m.group(1).lower()}' line")

    def path(self, path: str, suffix: str = "") -> str:
        """Checks on the path name itself. Returns the location to report the
        file under: the path, or its hash when the path name has a finding."""
        hits = []
        if any(rx.search("/" + path) for rx in PATH_NAME_RES):
            hits.append(("abs-path", "absolute local path in the path"))
        if bad_email_columns(path):
            hits.append(("email", "email address not allowed in the path"))
        if MARKER_RE.search(path):
            hits.append(("suppression-marker", "inline gitleaks suppression marker in the path"))
        if any(ord(ch) > 127 and ch not in NON_ASCII_ALLOW for ch in path):
            hits.append(("non-ascii", "non-ASCII character in the path"))
        if any(ord(ch) < 0x20 or ord(ch) == 0x7F for ch in path):
            hits.append(("path-control", "control character in the path"))
        where = path_location(path, suffix) if hits else path + suffix
        for category, detail in hits:
            self.add(where, 0, category, detail)
        if path.rsplit("/", 1)[-1].lower() == ".gitleaksignore":
            self.add(where, 0, "gitleaksignore", ".gitleaksignore file is not allowed")
        return where

    def blob(self, path: str, data: bytes, where: str, *, pin: bool = True) -> None:
        """Checks on the bytes of one file."""
        base = path.rsplit("/", 1)[-1].lower()
        if pin and base in PINNED:
            digest = hashlib.sha256(data).hexdigest()
            if digest != PINNED[base]:
                self.add(where, 0, "pin", f"{base} differs from the canonical content (sha256 {digest})")
        if b"\0" in data:
            self.add(where, 0, "binary", "binary file")
            return
        cr = data.find(b"\r")
        if cr >= 0:
            self.add(where, data.count(b"\n", 0, cr) + 1, "crlf", "CR byte in a text file")
        self.text(data.decode("utf-8", "replace"), where)

    def identity(self, raw: bytes, where: str) -> None:
        """Author and committer emails in a raw commit object."""
        emails: dict[str, str] = {}
        for line in raw.partition(b"\n\n")[0].split(b"\n"):
            m = IDENTITY_RE.fullmatch(line)
            if m:
                emails.setdefault(m.group(1).decode(), m.group(2).decode("utf-8", "surrogateescape"))
        for role in ("author", "committer"):
            if not identity_allowed(emails.get(role, "")):
                self.add(where, 0, "identity-email", f"{role} email is not a GitHub noreply address")

    def header(self, raw: bytes, where: str) -> None:
        """Leak checks on every raw header line of a commit object, signature
        blocks and the identity lines included, so an armor header or a
        second identity line is covered too. No non-ASCII check: names may be
        non-ASCII."""
        for n, line in enumerate(raw.partition(b"\n\n")[0].split(b"\n"), 1):
            self.leaks(line.decode("utf-8", "replace"), where, n)


def split_z(raw: bytes) -> list[str]:
    return [p.decode("utf-8", "surrogateescape") for p in raw.split(b"\0") if p]


def scan_tree(top: str, rep: Report) -> None:
    raw = git(top, "ls-files", "-z", "--cached", "--others", "--exclude-standard")
    paths = sorted(set(split_z(raw)))
    # The root pins are read from disk whether git lists them or not, so an
    # ignore rule cannot hide a changed one.
    for name, digest in PINNED.items():
        full = os.path.join(top, name)
        if os.path.islink(full):
            data = os.fsencode(os.readlink(full))
        elif os.path.isfile(full):
            with open(full, "rb") as f:
                data = f.read()
        else:
            rep.add(name, 0, "pin", f"{name} is missing")
            continue
        actual = hashlib.sha256(data).hexdigest()
        if actual != digest:
            rep.add(name, 0, "pin", f"{name} differs from the canonical content (sha256 {actual})")
    for path in paths:
        where = rep.path(path)
        full = os.path.join(top, *path.split("/"))
        if os.path.islink(full):
            data = os.fsencode(os.readlink(full))
        elif os.path.isfile(full):
            with open(full, "rb") as f:
                data = f.read()
        else:
            continue  # deleted from the working tree, or a submodule folder
        rep.files += 1
        rep.blob(path, data, where, pin=path not in PINNED)


def resolve(top: str, rev: str) -> str:
    try:
        return git(top, "rev-parse", "--verify", "--end-of-options", f"{rev}^{{commit}}").decode().strip()
    except GitError:
        raise GitError(f"not a commit: {rev}") from None


def scan_range(top: str, spec: str, rep: Report) -> None:
    base_rev, sep, head_rev = spec.partition("..")
    if not sep or not base_rev or not head_rev or head_rev.startswith("."):
        raise UsageError(f"--range must be BASE..HEAD, got {spec!r}")
    base = resolve(top, base_rev)
    head = resolve(top, head_rev)
    # Parents before children, so a file is reported at the commit that added it.
    rows = git(top, "rev-list", "--topo-order", "--reverse", "--parents", f"{base}..{head}").decode().split("\n")
    seen: set[tuple[str, str]] = set()
    for row in filter(None, rows):
        sha, *parents = row.split()
        short = sha[:12]
        raw = git(top, "cat-file", "commit", sha)
        rep.commits += 1
        rep.identity(raw, f"commit/{short}")
        rep.header(raw, f"commit/{short}/header")
        message = raw.partition(b"\n\n")[2]
        rep.text(message.decode("utf-8", "replace"), f"commit/{short}", message=True)
        opts = ("diff-tree", "-r", "-z", "--no-commit-id", "--no-renames", "--diff-filter=d")
        if parents:
            diff = git(top, *opts, parents[0], sha)
        else:
            diff = git(top, *opts, "--root", sha)
        fields = split_z(diff)
        for meta, path in zip(fields[0::2], fields[1::2]):
            _, new_mode, _, blob, _ = meta.lstrip(":").split(" ")
            if (path, blob) in seen:
                continue
            seen.add((path, blob))
            where = rep.path(path, f"@{short}")
            if new_mode == MODE_GITLINK:
                continue
            rep.blob(path, git(top, "cat-file", "blob", blob), where)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="hygiene.py", description="Public repository hygiene check.")
    ap.add_argument("--range", metavar="BASE..HEAD", help="also check the commits of this range")
    args = ap.parse_args(argv)
    rep = Report()
    error = None
    try:
        top = git(None, "rev-parse", "--show-toplevel").decode("utf-8", "surrogateescape").strip()
        scan_tree(top, rep)
        if args.range is not None:
            scan_range(top, args.range, rep)
    except (UsageError, GitError) as e:
        error = safe(str(e))
    except Exception as e:
        # The message of an unexpected error may carry a path or file content.
        error = f"unexpected {type(e).__name__}"
    for line in rep.lines:
        print(line)
    sys.stdout.flush()
    commits = f", {rep.commits} commits" if args.range is not None else ""
    print(f"hygiene: checked {rep.files} files{commits}", file=sys.stderr)
    if error is not None:
        print(f"hygiene.py: {error}", file=sys.stderr)
        return 2
    if rep.lines:
        print(f"hygiene: {len(rep.lines)} finding(s)", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
